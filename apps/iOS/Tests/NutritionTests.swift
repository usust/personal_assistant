import Foundation

/// 饮食估算纯逻辑测试，只使用虚构食物与内存JSON，不读取照片、不调用AI。
@main struct NutritionTests {
    /// 运行边界测试；参数：无；返回值：无；失败抛错或终止进程，不访问真实健康数据。
    static func main() throws {
        precondition(!NutritionMath.validGoal(999) && NutritionMath.validGoal(1000))
        precondition(NutritionMath.validGoal(6000) && !NutritionMath.validGoal(6001))
        precondition(!NutritionMath.validGoal(.nan) && !NutritionMath.validGoal(.infinity))
        precondition(NutritionMath.comparison(recorded: 1200, adding: 900, goal: 2000).contains("高于目标约 100"))
        precondition(NutritionMath.comparison(recorded: 1200, adding: 800, goal: 2000).contains("达到每日目标"))
        precondition(NutritionMath.comparison(recorded: 1200, goal: 2000).contains("低于目标约 800"))
        precondition(NutritionMath.comparison(recorded: 0, goal: nil).contains("设置每日"))
        precondition(NutritionMath.comparison(recorded: 0, goal: 0).contains("设置每日"))
        precondition(NutritionMath.comparison(recorded: -.infinity, goal: 2000) == "摄入数据无效")
        precondition(NutritionMath.comparison(recorded: -1, goal: 2000) == "摄入数据无效")
        precondition(NutritionMath.comparison(recorded: 0, adding: .nan, goal: 2000) == "摄入数据无效")
        // 巨大但有限的输入不转换为Int，避免越界崩溃；非有限合计明确拒绝。
        precondition(NutritionMath.comparison(recorded: 1e100, goal: 2000).contains("高于"))
        precondition(NutritionMath.comparison(recorded: .greatestFiniteMagnitude, adding: .greatestFiniteMagnitude, goal: 2000) == "摄入数据无效")
        let rice = MealItem(name: "米饭", grams: 200, calories: 260)
        precondition(rice.valid)
        precondition(!MealItem(name: " ", grams: 200, calories: 260).valid)
        precondition(!MealItem(name: "米饭", grams: 0, calories: 260).valid)
        precondition(!MealItem(name: "米饭", grams: .nan, calories: 260).valid)
        precondition(!MealItem(name: "米饭", grams: 200, calories: .infinity).valid)
        precondition(!MealItem(name: String(repeating: "饭", count: 41), grams: 1, calories: 1).valid)
        precondition(!MealItem(name: "米饭", grams: 10001, calories: 1).valid)
        precondition(!MealItem(name: "米饭", grams: 100, calories: 20001).valid)
        var draft = MealItemDraft(rice)
        draft.changeGrams(""); precondition(draft.item == nil)
        draft.changeGrams("1"); draft.changeGrams("10"); draft.changeGrams("100")
        precondition(draft.item?.calories == 130 && draft.item?.grams == 100)
        draft.changeCalories("200"); draft.changeGrams("200")
        precondition(draft.item?.calories == 400)
        draft.changeCalories("invalid"); precondition(draft.item == nil)
        draft.changeCalories("0"); precondition(draft.item == nil)
        let tiny = MealItemDraft(MealItem(name: "测试", grams: 0.00001, calories: 0.00001))
        precondition(tiny.item != nil && tiny.item?.grams == 0.00001)
        precondition(MealItemDraft.number(1000) == "1000")
        precondition(!NutritionMath.validMeal([], note: ""))
        precondition(NutritionMath.validMeal([MealItemDraft(rice)], note: "估算"))
        precondition(!NutritionMath.validMeal(Array(repeating: MealItemDraft(rice), count: 21), note: ""))
        precondition(!NutritionMath.validMeal([MealItemDraft(rice)], note: String(repeating: "饭", count: 501)))
        let decoder = JSONDecoder()
        let raw = Data(#"{"recognized":true,"items":[{"name":"米饭","grams":200,"calories":260}],"note":"估算"}"#.utf8)
        let recognized = try decoder.decode(MealAnalysisResult.self, from: raw)
        precondition(recognized.valid)
        let nonfood = MealAnalysisResult(recognized: false, items: [], note: "不是食物")
        precondition(nonfood.valid)
        precondition(!MealAnalysisResult(recognized: false, items: [rice], note: "").valid)
        precondition(!MealAnalysisResult(recognized: true, items: [], note: "").valid)
        let missing = Data(#"{"recognized":true,"items":[{"name":"饭","grams":100,"calories":null}],"note":""}"#.utf8)
        precondition((try? decoder.decode(MealAnalysisResult.self, from: missing)) == nil)
        let empty = try decoder.decode(NutritionOverview.self, from: Data(#"{"daily_goal":null,"meals":[]}"#.utf8))
        precondition(empty.daily_goal == nil && empty.calories == 0)
        let day = try decoder.decode(NutritionOverview.self, from: Data(#"{"daily_goal":2000,"meals":[{"id":"a","date":"2026-10-17","meal_type":"lunch","items":[{"name":"饭","grams":100,"calories":120},{"name":"菜","grams":100,"calories":100}],"note":"","created_at":"2026-10-17T12:00:00Z"}]}"#.utf8))
        precondition(day.calories == 220)
        print("Nutrition tests passed")
    }
}
